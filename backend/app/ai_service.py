import os
from typing import Iterator

from dotenv import load_dotenv
from google import genai


load_dotenv()

API_KEY = os.getenv("GEMINI_API_KEY")

if not API_KEY:
    raise RuntimeError(
        "GEMINI_API_KEY is missing. Check your backend .env file."
    )

client = genai.Client(api_key=API_KEY)


# BIBBLE model configuration
MODEL_ARGON = "gemini-4-argon"
MODEL_HYDROGEN = "gemini-4-hydrogen"
MODEL_FLASH = "gemini-3.8-flash"


def choose_model(action: str, prompt: str) -> str:
    """
    Select a Gemini model based on the creative task.
    """

    action = action.lower().strip()

    deep_actions = {
        "deep_analysis",
        "story_architecture",
        "character_psychology",
        "symbolism",
        "deep_critique",
    }

    lightweight_actions = {
        "summarize",
        "rewrite",
        "grammar",
        "shorten",
    }

    if action in deep_actions:
        return MODEL_ARGON

    if action in lightweight_actions:
        return MODEL_FLASH

    return MODEL_HYDROGEN


def stream_gemini_response(
    prompt: str,
    action: str = "chat",
) -> Iterator[str]:
    """
    Stream text generated by Gemini.

    If the selected model fails before producing text,
    try the configured fallback models.
    """

    selected_model = choose_model(action, prompt)

    fallback_models = {
        MODEL_ARGON: [MODEL_HYDROGEN, MODEL_FLASH],
        MODEL_HYDROGEN: [MODEL_FLASH],
        MODEL_FLASH: [MODEL_HYDROGEN],
    }

    models_to_try = [
        selected_model,
        *fallback_models.get(selected_model, []),
    ]

    for model_name in models_to_try:
        generated_text = False

        try:
            stream = client.interactions.create(
                model=model_name,
                input=prompt,
                stream=True,
            )

            for event in stream:
                if event.event_type == "step.delta":
                    if event.delta.type == "text":
                        chunk = event.delta.text

                        if chunk:
                            generated_text = True
                            yield chunk

            return

        except Exception:
            if generated_text:
                raise

            continue

    raise RuntimeError(
        "BIBBLE could not generate a response. "
        "Please check your Gemini API configuration and try again."
    )